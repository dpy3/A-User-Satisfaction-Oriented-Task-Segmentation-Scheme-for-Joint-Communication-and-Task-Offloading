function Validate_MCA_Capacity_Phase(slot_tbl, run_tbl, cfg, require_complete)
if nargin < 4, require_complete = false; end
assert(height(slot_tbl) > 0 && height(run_tbl) > 0, 'MCA:CapacityPhaseEmpty', ...
    'Capacity-phase tables are empty.');
required = {'Profile','NormalizedLoadTarget','CapacityRef','RealizedNormalizedLoad'};
assert(all(ismember(required, slot_tbl.Properties.VariableNames)), 'MCA:CapacityPhaseSchema', ...
    'Capacity-phase profile/load fields are missing.');
assert(all(slot_tbl.ResourceViolation == 0), 'MCA:CapacityPhaseResourceViolation', ...
    'Capacity-phase replay contains resource violations.');
assert(all(abs(slot_tbl.CompositeViolation - (100 - slot_tbl.Sat)) < 1e-8), ...
    'MCA:CapacityPhaseCompositeIdentity', 'Composite identity failed.');
assert(all(slot_tbl.OfferedTasks == slot_tbl.BacklogIn + slot_tbl.Arrivals), ...
    'MCA:CapacityPhaseFlowIdentity', 'Offered-task flow identity failed.');
classified = slot_tbl.MemoryBlockCount + slot_tbl.IntrinsicLatencyBlockCount + ...
    slot_tbl.SpilloverBlockCount + slot_tbl.FeasibleMissedCount;
assert(all(classified == slot_tbl.OfferedTasks - slot_tbl.SatisfiedCount), ...
    'MCA:CapacityPhaseFailurePartition', 'Failure causes do not partition unsatisfied tasks.');
assert(all(slot_tbl.N == round(slot_tbl.CapacityRef .* slot_tbl.NormalizedLoadTarget)), ...
    'MCA:CapacityPhaseLoadMapping', 'N does not match the frozen capacity/load mapping.');
assert(all(abs(slot_tbl.RealizedNormalizedLoad - slot_tbl.N ./ slot_tbl.CapacityRef) < 1e-12), ...
    'MCA:CapacityPhaseRealizedLoad', 'Realized normalized load is inconsistent.');

slot_keys = strcat(slot_tbl.Profile, "/", string(slot_tbl.NormalizedLoadTarget), "/", ...
    string(slot_tbl.Run), "/", string(slot_tbl.Slot), "/", slot_tbl.Algorithm);
run_keys = strcat(run_tbl.Profile, "/", string(run_tbl.NormalizedLoadTarget), "/", ...
    string(run_tbl.Run), "/", run_tbl.Algorithm);
assert(numel(unique(slot_keys)) == height(slot_tbl), 'MCA:CapacityPhaseDuplicateKey', ...
    'Duplicate capacity-phase slot key.');
assert(numel(unique(run_keys)) == height(run_tbl), 'MCA:CapacityPhaseDuplicateRun', ...
    'Duplicate capacity-phase run key.');

[groups, ~] = findgroups(slot_tbl.Profile, slot_tbl.NormalizedLoadTarget, ...
    slot_tbl.Run, slot_tbl.Slot);
counts = splitapply(@numel, slot_tbl.Algorithm, groups);
assert(all(counts == numel(cfg.algorithms)), 'MCA:CapacityPhaseAlgorithmCount', ...
    'A capacity-phase slot lacks algorithms.');
for g = unique(groups)'
    assert(isequal(sort(slot_tbl.Algorithm(groups == g)), sort(string(cfg.algorithms(:)))), ...
        'MCA:CapacityPhaseAlgorithmSet', 'Algorithm set differs within a slot.');
    assert(numel(unique(slot_tbl.EnvironmentSeed(groups == g))) == 1, ...
        'MCA:CapacityPhasePairing', 'Algorithms do not share an environment seed.');
end
assert(all(run_tbl.Slots == cfg.replay_slots), 'MCA:CapacityPhaseSlotCount', ...
    'Run summary has the wrong slot count.');

if require_complete
    expected_cells = numel(cfg.infrastructure_profiles) * numel(cfg.normalized_loads) * ...
        numel(cfg.required_replay_runs);
    assert(height(slot_tbl) == expected_cells * cfg.replay_slots * numel(cfg.algorithms), ...
        'MCA:CapacityPhaseIncomplete', 'Capacity-phase slot package is incomplete.');
    assert(height(run_tbl) == expected_cells * numel(cfg.algorithms), ...
        'MCA:CapacityPhaseIncomplete', 'Capacity-phase run package is incomplete.');
end
fprintf('CAPACITY-PHASE VALIDATION PASS: %d slot rows, %d run rows, complete=%d.\n', ...
    height(slot_tbl), height(run_tbl), require_complete);
end
