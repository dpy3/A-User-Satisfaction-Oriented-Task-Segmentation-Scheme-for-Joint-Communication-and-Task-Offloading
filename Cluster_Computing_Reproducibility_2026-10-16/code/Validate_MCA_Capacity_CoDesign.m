function Validate_MCA_Capacity_CoDesign(slot_tbl, run_tbl, cfg, require_complete)
if nargin < 4, require_complete = false; end
assert(height(slot_tbl) > 0 && height(run_tbl) > 0, 'MCA:CoDesignEmpty', ...
    'Co-design tables are empty.');
assert(all(slot_tbl.ResourceViolation == 0), 'MCA:CoDesignResourceViolation', ...
    'Co-design replay contains resource violations.');
assert(all(abs(slot_tbl.CompositeViolation - (100 - slot_tbl.Sat)) < 1e-8), ...
    'MCA:CoDesignCompositeIdentity', 'Composite identity failed.');
assert(all(slot_tbl.OfferedTasks == slot_tbl.BacklogIn + slot_tbl.Arrivals), ...
    'MCA:CoDesignFlowIdentity', 'Offered-task flow identity failed.');
classified = slot_tbl.AdmissionRejectCount + slot_tbl.MemoryBlockCount + ...
    slot_tbl.IntrinsicLatencyBlockCount + slot_tbl.SpilloverBlockCount + slot_tbl.FeasibleMissedCount;
assert(all(classified == slot_tbl.OfferedTasks - slot_tbl.SatisfiedCount), ...
    'MCA:CoDesignFailurePartition', 'Failures and admission rejects do not partition unsatisfied tasks.');
assert(all(slot_tbl.N == round(slot_tbl.CapacityRef .* slot_tbl.NormalizedLoadTarget)), ...
    'MCA:CoDesignLoadMapping', 'N does not match frozen capacity/load mapping.');
assert(all(slot_tbl.AdmissionRejectCount >= 0 & slot_tbl.AdmissionRejectCount == floor(slot_tbl.AdmissionRejectCount)), ...
    'MCA:CoDesignRejectCount', 'Admission rejects must be nonnegative integers.');
assert(all(slot_tbl.CapacityBoost >= 1), 'MCA:CoDesignCapacityBoost', ...
    'Capacity boost cannot be below one.');

slot_keys = strcat(slot_tbl.Profile, "/", string(slot_tbl.NormalizedLoadTarget), "/", ...
    string(slot_tbl.Run), "/", string(slot_tbl.Slot), "/", slot_tbl.Algorithm);
assert(numel(unique(slot_keys)) == height(slot_tbl), 'MCA:CoDesignDuplicateKey', ...
    'Duplicate co-design slot key.');
[groups, ~] = findgroups(slot_tbl.Profile, slot_tbl.NormalizedLoadTarget, ...
    slot_tbl.Run, slot_tbl.Slot);
counts = splitapply(@numel, slot_tbl.Algorithm, groups);
assert(all(counts == numel(cfg.algorithms)), 'MCA:CoDesignAlgorithmCount', ...
    'A co-design slot lacks policies.');
for g = unique(groups)'
    assert(isequal(sort(slot_tbl.Algorithm(groups == g)), sort(string(cfg.algorithms(:)))), ...
        'MCA:CoDesignAlgorithmSet', 'Policy set differs within a slot.');
    assert(numel(unique(slot_tbl.EnvironmentSeed(groups == g))) == 1, ...
        'MCA:CoDesignPairing', 'Policies do not share an environment seed.');
end
assert(all(run_tbl.Slots == cfg.replay_slots), 'MCA:CoDesignSlotCount', ...
    'Run summary has wrong slot count.');
if require_complete
    if isfield(cfg, 'codesign_profile_loads')
        profile_cells = 0;
        for p = 1:numel(cfg.infrastructure_profiles)
            profile_cells = profile_cells + numel(cfg.codesign_profile_loads.(cfg.infrastructure_profiles{p}));
        end
    else
        profile_cells = numel(cfg.infrastructure_profiles) * numel(cfg.normalized_loads);
    end
    cells = profile_cells * numel(cfg.required_replay_runs);
    assert(height(slot_tbl) == cells * cfg.replay_slots * numel(cfg.algorithms), ...
        'MCA:CoDesignIncomplete', 'Co-design slot package is incomplete.');
    assert(height(run_tbl) == cells * numel(cfg.algorithms), ...
        'MCA:CoDesignIncomplete', 'Co-design run package is incomplete.');
end
fprintf('CAPACITY CO-DESIGN VALIDATION PASS: %d slot rows, %d run rows, complete=%d.\n', ...
    height(slot_tbl), height(run_tbl), require_complete);
end
