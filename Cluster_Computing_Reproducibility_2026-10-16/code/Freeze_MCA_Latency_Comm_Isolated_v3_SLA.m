function Freeze_MCA_Latency_Comm_Isolated_v3_SLA()
root=fullfile(fileparts(mfilename('fullpath')),'Results', ...
    'CAPACITYPHASELATENCYISOLATEDV3SLA_FIXED5');
run_file=dir(fullfile(root,'CapacityPhase_RunLevel_*.csv'));
slot_file=dir(fullfile(root,'CapacityPhase_SlotLevel_*.csv'));
assert(isscalar(run_file) && isscalar(slot_file),'MCA:IsolatedV3SLAFiles', ...
    'Expected exactly one run-level and slot-level SLA file.');
runs=readtable(fullfile(run_file.folder,run_file.name),'TextType','string');
slots=readtable(fullfile(slot_file.folder,slot_file.name),'TextType','string');
assert(height(runs)==5 && all(runs.Run==(177:181)') && all(runs.Slots==100), ...
    'MCA:IsolatedV3SLARuns','Expected runs 177--181 with 100 slots.');
assert(height(slots)==500 && all(slots.ResourceViolation==0), ...
    'MCA:IsolatedV3SLAViolation','SLA replay must have 500 violation-free slots.');
mean_sat=mean(runs.MeanSat); sd_sat=std(runs.MeanSat,0);
frozen=table("latency_comm_isolated_v3",0.05,"ALMv9",5,100, ...
    mean_sat,sd_sat,mean_sat/100, ...
    'VariableNames',{'Profile','NormalizedLoadTarget','Algorithm','Runs','Slots', ...
    'MeanSat','SDSat','SLATarget'});
writetable(frozen,fullfile(root,'LatencyCommIsolatedV3_SLA_Frozen.csv'));
save(fullfile(root,'LatencyCommIsolatedV3_SLA_Frozen.mat'),'frozen','runs','slots');
fprintf('LATENCY COMM ISOLATED V3 SLA FROZEN: %.10f (SD %.4f pp)\n', ...
    frozen.SLATarget,frozen.SDSat);
disp(frozen);
end
