function row = MCA_Evaluate(theta, Task, Fog, Thing, DNN_Data, Pre, context)
if nargin < 7, context = 'unknown'; end
[N, M] = size(theta);
assert(N == size(Task, 1) && M == size(Fog, 1), 'MCA:ThetaShape', ...
    '%s: theta is %dx%d, expected %dx%d.', context, N, M, size(Task, 1), size(Fog, 1));
assert(all(isfinite(theta(:))), 'MCA:NonFiniteTheta', '%s: theta contains NaN/Inf.', context);
assert(all(theta(:) >= 0), 'MCA:NegativeTheta', '%s: theta contains negative values.', context);

[sat, viol, b, latency, sat_vec, viol_vec] = calculate_metrics_v2(theta, Task, Fog, Thing, DNN_Data, Pre);
detail = b.detail;
tol = 1e-9;
assert(all(sum(theta > 0, 2) <= 1), 'MCA:MultiAssignment', '%s: repair left multi-assigned tasks.', context);
assert(all(detail.timely_vec <= detail.admitted_vec), 'MCA:TimelyWithoutAdmission', '%s: timely task was not admitted.', context);
assert(all(detail.satisfied_vec <= detail.timely_vec), 'MCA:SatisfiedNotTimely', '%s: satisfied task missed deadline.', context);
assert(all(detail.satisfied_vec <= detail.admitted_vec), 'MCA:SatisfiedNotAdmitted', '%s: satisfied task was dropped.', context);
assert(abs(sat - mean(sat_vec) * 100) <= tol, 'MCA:SatIdentity', '%s: satisfaction identity failed.', context);
assert(abs(viol - mean(viol_vec) * 100) <= tol, 'MCA:ViolationIdentity', '%s: violation identity failed.', context);
assert(abs(b.composite_viol_rate - (100 - sat)) <= tol, 'MCA:CompositeIdentity', ...
    '%s: under binary semantics, composite violation must equal 100-satisfaction.', context);
classified_failures = b.memory_block_count + b.intrinsic_latency_block_count + ...
    b.spillover_block_count + b.feasible_missed_count;
assert(classified_failures == N - sum(sat_vec), 'MCA:FailureClassification', ...
    '%s: bottleneck causes do not partition unsatisfied tasks.', context);
bounded = [sat, viol, b.admission_rate, b.timely_rate_among_admitted, ...
    b.resource_viol_rate, b.deadline_viol_rate, b.composite_viol_rate, b.invalid_assign_rate];
assert(all(isfinite(bounded)) && all(bounded >= -tol & bounded <= 100 + tol), ...
    'MCA:MetricBounds', '%s: percentage metric outside [0,100].', context);

row = struct('Sat', sat, 'ViolSelected', viol, 'Admission', b.admission_rate, ...
    'TimelyAmongAdmitted', b.timely_rate_among_admitted, ...
    'ResourceViolation', b.resource_viol_rate, 'DeadlineViolation', b.deadline_viol_rate, ...
    'CompositeViolation', b.composite_viol_rate, 'InvalidAssignment', b.invalid_assign_rate, ...
    'LatencyAdmitted', b.latency_admitted_all, 'LatencyTimely', b.latency_admitted_timely, ...
    'SatisfiedCount', sum(sat_vec), 'AdmittedCount', sum(detail.admitted_vec), ...
    'ResourceViolationCount', sum(detail.resource_viol_vec), 'TaskCount', N, ...
    'DeadlineMissCount', b.admitted_deadline_miss_count, ...
    'MemoryBlockCount', b.memory_block_count, ...
    'IntrinsicLatencyBlockCount', b.intrinsic_latency_block_count, ...
    'SpilloverBlockCount', b.spillover_block_count, ...
    'FeasibleMissedCount', b.feasible_missed_count, ...
    'LatencyVector', latency, 'SatisfiedVector', sat_vec);
if isfield(Pre, 'FullBacklogStreak')
    row.FullBacklogStreakIn = Pre.FullBacklogStreak;
else
    row.FullBacklogStreakIn = 0;
end
row.OverloadModeActive = false;
if isfield(Pre, 'ReplayScaleN') && isfield(Pre, 'BacklogIn')
    row.OverloadModeActive = (Pre.BacklogIn / max(1, Pre.ReplayScaleN) >= 0.75) || ...
        (row.FullBacklogStreakIn >= 2);
end
end
